-- Esquema inicial de La Acción.

create table app_user (
    id                    bigint generated by default as identity primary key,
    email                 varchar(254) not null,
    display_name          varchar(80)  not null,
    password_hash         varchar(255) not null,
    role                  varchar(20)  not null,
    enabled               boolean      not null default true,
    failed_login_attempts integer      not null default 0,
    locked_until          timestamptz,
    last_login_at         timestamptz,
    created_at            timestamptz  not null,
    updated_at            timestamptz  not null,
    constraint uq_app_user_email unique (email),
    constraint ck_app_user_role check (role in ('ADMIN', 'EDITOR'))
);

create table category (
    id          bigint generated by default as identity primary key,
    name        varchar(80)  not null,
    slug        varchar(100) not null,
    description varchar(300),
    sort_order  integer      not null default 0,
    constraint uq_category_slug unique (slug)
);

create table tag (
    id   bigint generated by default as identity primary key,
    name varchar(40) not null,
    slug varchar(60) not null,
    constraint uq_tag_slug unique (slug)
);

create table image (
    id           bigint generated by default as identity primary key,
    storage_key  varchar(200) not null,
    url          varchar(500) not null,
    content_type varchar(50)  not null,
    size_bytes   bigint       not null,
    width        integer,
    height       integer,
    uploaded_by  bigint       not null references app_user (id),
    created_at   timestamptz  not null,
    constraint uq_image_storage_key unique (storage_key)
);

create table article (
    id                 bigint generated by default as identity primary key,
    slug               varchar(160) not null,
    title              varchar(200) not null,
    dek                varchar(300),
    summary            varchar(600) not null,
    content_html       text         not null,
    status             varchar(20)  not null,
    byline             varchar(120),
    author_id          bigint       not null references app_user (id),
    category_id        bigint       not null references category (id),
    featured_image_id  bigint references image (id),
    featured_image_alt varchar(250),
    featured           boolean      not null default false,
    reading_minutes    integer      not null default 1,
    published_at       timestamptz,
    created_at         timestamptz  not null,
    updated_at         timestamptz  not null,
    constraint uq_article_slug unique (slug),
    constraint ck_article_status check (status in ('DRAFT', 'PUBLISHED')),
    constraint ck_article_published_at check (status = 'DRAFT' or published_at is not null)
);

create index ix_article_public on article (published_at desc) where status = 'PUBLISHED';
create index ix_article_category on article (category_id);
create index ix_article_author on article (author_id);

create table article_tag (
    article_id bigint not null references article (id) on delete cascade,
    tag_id     bigint not null references tag (id) on delete cascade,
    primary key (article_id, tag_id)
);

create index ix_article_tag_tag on article_tag (tag_id);

create table announcement (
    id          bigint generated by default as identity primary key,
    section     varchar(90)  not null,
    title       varchar(110) not null,
    description varchar(280) not null,
    details     varchar(180),
    url         varchar(500),
    event_date  date         not null,
    stamp       varchar(35)  not null,
    tone        varchar(10)  not null,
    visible     boolean      not null default true,
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null,
    constraint ck_announcement_tone check (tone in ('IVORY', 'RED', 'GOLD', 'DARK'))
);

create index ix_announcement_board on announcement (event_date) where visible;

create table poll (
    id          bigint generated by default as identity primary key,
    question    varchar(300) not null,
    description varchar(1000),
    video_url   varchar(500),
    status      varchar(10)  not null,
    closes_at   timestamptz,
    created_by  bigint       not null references app_user (id),
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null,
    constraint ck_poll_status check (status in ('DRAFT', 'OPEN', 'CLOSED'))
);

create table poll_option (
    id          bigint generated by default as identity primary key,
    poll_id     bigint       not null references poll (id) on delete cascade,
    label       varchar(200) not null,
    sort_order  integer      not null,
    votes_count bigint       not null default 0
);

create index ix_poll_option_poll on poll_option (poll_id);

-- Control de voto duplicado. A propósito NO guarda qué opción se votó:
-- la opinión (dato de categoría especial, art. 9 RGPD) queda desvinculada de quien vota.
-- voter_hash = HMAC-SHA256(secreto, encuesta + IP); las filas se borran al cerrar la encuesta.
create table poll_vote (
    id         bigint generated always as identity primary key,
    poll_id    bigint      not null references poll (id) on delete cascade,
    voter_hash varchar(64) not null,
    created_at timestamptz not null,
    constraint uq_poll_vote unique (poll_id, voter_hash)
);

create table audit_log (
    id          bigint generated by default as identity primary key,
    actor_id    bigint,
    actor_email varchar(254),
    action      varchar(60) not null,
    entity_type varchar(40),
    entity_id   varchar(60),
    summary     varchar(500),
    created_at  timestamptz not null
);

create index ix_audit_log_created on audit_log (created_at desc);
